// Draw a single character at (x, y) using filled square blocks of size `scale`.
// Converts lowercase to uppercase automatically.
// Characters outside ASCII 32-90 are rendered as space.
static void prim_draw_char(char c, uint16_t x, uint16_t y, uint8_t scale)
{
  if (c >= 'a' && c <= 'z') c = (char)(c - 32);
  if (c < 32 || c > 90)     c = 32;
  const uint8_t* glyph = SD_MISSING_FONT[(uint8_t)(c - 32)];
  for (uint8_t row = 0; row < 8; row++) {
    uint8_t bits = glyph[row];
    for (uint8_t col = 0; col < 8; col++) {
      if (bits & (0x80u >> col)) {
        screen.colorize_region(
          Dim(scale, scale),
          Pos((uint16_t)(x + col * scale), (uint16_t)(y + row * scale)),
          Screen::BLACK_COLOR);
      }
    }
  }
}

// Measure the pixel width of a string at the given scale.
static uint16_t prim_text_width(const char* text, uint8_t scale)
{
  uint16_t n = 0;
  while (*text++) n++;
  return (uint16_t)(n * 9u * scale);  // 8px glyph + 1px gap per char
}

// Draw a string horizontally centred on the screen at row y, using scale.
static void prim_draw_text_centered(const char* text, uint16_t y, uint8_t scale)
{
  uint16_t tw = prim_text_width(text, scale);
  uint16_t x  = (Screen::get_width() > tw) ? (uint16_t)((Screen::get_width() - tw) / 2) : 0;
  while (*text) {
    prim_draw_char(*text++, x, y, scale);
    x += (uint16_t)(9u * scale);
  }
}
